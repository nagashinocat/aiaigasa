export function getStory(id) {
  return STORIES.find((s) => s.id === id) || STORIES[0];
}

export function lineAt(story, doki) {
  let found = null;
  story.lines.forEach((line, index) => { if (line.at <= doki) found = { index, line }; });
  return found;
}

export function isClimax(story, doki) {
  const cur = lineAt(story, doki);
  return !!(cur && cur.line.climax);
}
